# Builds the full release set: GPU vrad3.exe, vrad3_settings.exe, the vrad2.exe shim and the OpenImageDenoise.dll shim, into dist.
param(
    [string]$VisualStudio = '',   # blank = find automatically
    [string]$Dxc = ''             # blank = find automatically
)
$ErrorActionPreference = 'Stop'
trap { Write-Host "ERROR: $($_.Exception.Message)" -ForegroundColor Red; exit 1 }
. (Join-Path $PSScriptRoot 'BuildTools.ps1')
$VisualStudio = Resolve-VisualStudio $VisualStudio
$Dxc = Resolve-Dxc $Dxc
$taskRoot = Split-Path -Parent $PSScriptRoot
$buildDir = Join-Path $taskRoot 'artifacts\capture-build'
$dist = Join-Path $taskRoot 'dist'
New-Item -ItemType Directory -Force -Path $buildDir,$dist | Out-Null
$vcvars = Join-Path $VisualStudio 'VC\Auxiliary\Build\vcvars64.bat'
$version = (Get-Content -LiteralPath (Join-Path $taskRoot 'VERSION') -Raw).Trim()
Set-Content -LiteralPath (Join-Path $buildDir 'version.h') -Value "#define VRAD3_VERSION `"$version`"" -Encoding ascii
# Three lighting shader variants are compiled in (standard, experimental, CS2 estimator); the wrapper picks one at run time.
$shader = Join-Path $PSScriptRoot 'gpu_lighting.hlsl'
& $Dxc -T cs_6_5 -E main -D VRAD3_EXPERIMENTAL=0 -Fh (Join-Path $buildDir 'lighting_embedded.h') -Vn g_lightingShader $shader
if ($LASTEXITCODE -ne 0) { throw 'Embedded lighting shader compilation failed.' }
& $Dxc -T cs_6_5 -E main -D VRAD3_EXPERIMENTAL=1 -Fh (Join-Path $buildDir 'lighting_embedded_full.h') -Vn g_lightingShaderFull $shader
if ($LASTEXITCODE -ne 0) { throw 'Embedded lighting shader compilation failed.' }
& $Dxc -T cs_6_5 -E main -D VRAD3_EXPERIMENTAL=0 -D VRAD3_CS2=1 -Fh (Join-Path $buildDir 'lighting_embedded_cs2.h') -Vn g_lightingShaderCs2 $shader
if ($LASTEXITCODE -ne 0) { throw 'Embedded lighting shader compilation failed.' }
$batch = Join-Path $buildDir 'build.cmd'
@"
@echo off
call "$vcvars"
if errorlevel 1 exit /b 1
cl /nologo /std:c++17 /EHsc /W4 /O2 /GL /Brepro /d1trimfile:`"$PSScriptRoot\\`" /MT /DVRAD3_STATIC_GPU /I"$buildDir" "$(Join-Path $PSScriptRoot 'vrad3_capture.cpp')" "$(Join-Path $PSScriptRoot 'gpu_lighting.cpp')" /Fe:vrad3_hammer.exe /link /LTCG /Brepro /MAP:vrad3.map /OPT:REF /OPT:ICF /SUBSYSTEM:WINDOWS /ENTRY:wmainCRTStartup
exit /b %errorlevel%
"@ | Set-Content -LiteralPath $batch -Encoding ascii
Push-Location $buildDir
try {
    & cmd.exe /c $batch
    if ($LASTEXITCODE -ne 0) { throw 'vrad3.exe build failed.' }
} finally { Pop-Location }
Copy-Item -LiteralPath (Join-Path $buildDir 'vrad3_hammer.exe') -Destination (Join-Path $dist 'vrad3.exe')
Copy-Item -LiteralPath (Join-Path $buildDir 'vrad3.map') -Destination (Join-Path $dist 'vrad3.map')
$iniPath = Join-Path $PSScriptRoot 'vrad3_gpu.example.ini'
$iniTemplate = (Get-Content -LiteralPath $iniPath -Raw).TrimEnd([char[]]"`r`n")
Copy-Item -LiteralPath $iniPath -Destination (Join-Path $dist 'vrad3_gpu.example.ini')
# The ini template is embedded in the settings app as raw string pieces, split to stay under the compiler's string literal size limit.
$pieces = New-Object System.Collections.Generic.List[string]; $piece = ''
foreach ($line in ($iniTemplate -split "`r?`n")) {
    if ($piece.Length + $line.Length -gt 8000) { $pieces.Add($piece); $piece = '' }
    $piece += $line + "`n"
}
$pieces.Add($piece)
$header = "// Generated by Build-SingleExe.ps1 from the vrad3_gpu.ini template.`nstatic const char kSettingsTemplate[]=`n" +
    (($pieces | ForEach-Object { 'R"ini(' + $_ + ')ini"' }) -join "`n") + ";`n"
Set-Content -LiteralPath (Join-Path $buildDir 'settings_template.h') -Value $header -Encoding ascii
$batch = Join-Path $buildDir 'build_settings.cmd'
@"
@echo off
call "$vcvars" >nul
if errorlevel 1 exit /b 1
cl /nologo /std:c++17 /EHsc /W4 /O2 /MT /DUNICODE /D_UNICODE /Brepro /d1trimfile:`"$PSScriptRoot\\`" /I"$buildDir" "$(Join-Path $PSScriptRoot 'vrad3_settings.cpp')" /Fe:vrad3_settings.exe /link /Brepro /SUBSYSTEM:WINDOWS /MANIFEST:EMBED
exit /b %errorlevel%
"@ | Set-Content -LiteralPath $batch -Encoding ascii
Push-Location $buildDir
try {
    & cmd.exe /c $batch
    if ($LASTEXITCODE -ne 0) { throw 'Settings app build failed.' }
} finally { Pop-Location }
Copy-Item -LiteralPath (Join-Path $buildDir 'vrad3_settings.exe') -Destination (Join-Path $dist 'vrad3_settings.exe')
$batch = Join-Path $buildDir 'build_vrad2.cmd'
@"
@echo off
call "$vcvars" >nul
if errorlevel 1 exit /b 1
cl /nologo /std:c++17 /EHsc /W4 /O2 /MT /DUNICODE /D_UNICODE /Brepro /d1trimfile:`"$PSScriptRoot\\`" "$(Join-Path $PSScriptRoot 'vrad2_shim.cpp')" /Fe:vrad2.exe /link /Brepro /SUBSYSTEM:CONSOLE /MANIFEST:EMBED
exit /b %errorlevel%
"@ | Set-Content -LiteralPath $batch -Encoding ascii
Push-Location $buildDir
try {
    & cmd.exe /c $batch
    if ($LASTEXITCODE -ne 0) { throw 'vrad2 shim build failed.' }
} finally { Pop-Location }
Copy-Item -LiteralPath (Join-Path $buildDir 'vrad2.exe') -Destination (Join-Path $dist 'vrad2.exe')
Copy-Item -LiteralPath (Join-Path $taskRoot 'setup\Setup.cmd'),(Join-Path $taskRoot 'setup\Setup.ps1') -Destination $dist
& (Join-Path $PSScriptRoot 'oidn_shim\Build-OidnShim.ps1') -VisualStudio $VisualStudio
